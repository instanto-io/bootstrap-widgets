// Maintainer-only: node build-tools/vendor-calendar-interactions.mjs /path/to/jquery-ui-1.13.3
// The argument is the extracted official jquery-ui npm package, not jquery-ui-dist.
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve, posix} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';

const upstream = resolve(process.argv[2]);
const metadata = JSON.parse(readFileSync(resolve(upstream, 'package.json'), 'utf8'));
if (metadata.name !== 'jquery-ui' || metadata.version !== '1.13.3') {
  throw new Error('Expected the official jquery-ui 1.13.3 package');
}
const visited = new Set(), modules = [];
function include(name) {
  if (visited.has(name)) return;
  visited.add(name);
  if (name.startsWith('../') || name.startsWith('/')) throw new Error('Unexpected dependency');
  const source = readFileSync(resolve(upstream, 'ui', name + '.js'), 'utf8');
  const dependencies = source.match(/define\(\s*\[([\s\S]*?)\]/);
  if (!dependencies) throw new Error('Missing dependency declaration: ' + name);
  for (const [, dependency] of dependencies[1].matchAll(/"([^"]+)"/g)) {
    if (dependency !== 'jquery') include(posix.normalize(posix.join(posix.dirname(name), dependency)));
  }
  modules.push({name, source});
}
include('widgets/draggable');
include('widgets/resizable');
const header = '/*! jQuery UI 1.13.3 — calendar drag/resize subset. MIT license.\n'
  + ' * Generated by build-tools/vendor-calendar-interactions.mjs from official upstream sources.\n'
  + ' * Modules: ' + modules.map(m => m.name).join(', ') + '\n */\n';
const bundle = header + modules.map(m => m.source).join('\n;\n');
const directory = resolve(dirname(fileURLToPath(import.meta.url)),
  '../gwt/gwt-bootstrap3-extras/src/main/java/org/gwtbootstrap3/extras/fullcalendar/client/resource/js');
writeFileSync(resolve(directory, 'jquery-ui-1.13.3-drag-resize.cache.js'), bundle);
writeFileSync(resolve(directory, 'JQUERY-UI-LICENSE.txt'), readFileSync(resolve(upstream, 'LICENSE.txt')));
console.log(`${modules.length} modules, ${Buffer.byteLength(bundle)} bytes, SHA-256 ${createHash('sha256').update(bundle).digest('hex')}`);
